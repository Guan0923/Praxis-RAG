def test_request_options_override_the_converter_endpoint(tmp_path: Path) -> None:
    captured: list[VisionSettings] = []
    client = ScriptedVisionClient(page_answers=[PAGE_TWO])

    def factory(settings: VisionSettings) -> ScriptedVisionClient:
        captured.append(settings)
        return client

    converter = VisionConverter(
        VisionSettings("http://env.local/v1", "env-key", "env-model"),
        client_factory=factory,
        page_dpi=100,
    )
    source = tmp_path / "source.pdf"
    source.write_bytes(build_pdf(pages=1))
    options = parse_options_payload(
        json.dumps(
            {
                "vision": {
                    "base_url": "http://req.local/v1",
                    "api_key": "req-key",
                    "model": "req-model",
                }
            }
        )
    )

    manifest = converter.convert(source, tmp_path / "artifacts", tmp_path / "scratch", options=options)

    assert captured and captured[0].model == "req-model"
    assert manifest["parser"]["model"] == "req-model"
    assert manifest["parser"]["endpoint"] == "req.local"
    assert "req-key" not in json.dumps(manifest)


def test_environment_endpoint_is_the_fallback(tmp_path: Path) -> None:
    captured: list[VisionSettings] = []

    def factory(settings: VisionSettings) -> ScriptedVisionClient:
        captured.append(settings)
        return ScriptedVisionClient(page_answers=[PAGE_TWO])

    converter = VisionConverter(
        VisionSettings("http://env.local/v1", "env-key", "env-model"),
        client_factory=factory,
        page_dpi=100,
    )
    source = tmp_path / "source.pdf"
    source.write_bytes(build_pdf(pages=1))

    manifest = converter.convert(source, tmp_path / "artifacts", tmp_path / "scratch")

    assert captured[0].model == "env-model"
    assert manifest["parser"]["model"] == "env-model"


def test_page_calls_run_on_bounded_worker_threads(tmp_path: Path) -> None:
    client = ScriptedVisionClient(page_answers=[PAGE_TWO])

    _run_converter(tmp_path, client, concurrency=2, pages=4)

    page_calls = [call for call in client.calls if call["kind"] == "page"]
    assert len(page_calls) == 4
    threads = {call["thread"] for call in page_calls}
    assert 1 <= len(threads) <= 2
    assert "MainThread" not in threads


def test_single_concurrency_runs_sequentially(tmp_path: Path) -> None:
    client = ScriptedVisionClient(page_answers=[PAGE_TWO])

    _run_converter(tmp_path, client, concurrency=1, pages=3)

    page_calls = [call for call in client.calls if call["kind"] == "page"]
    assert {call["thread"] for call in page_calls} == {"MainThread"}


def test_empty_page_emits_a_warning_and_still_succeeds(tmp_path: Path) -> None:
    client = ScriptedVisionClient(page_answers=[{"blocks": []}])

    manifest, artifacts = _run_converter(tmp_path, client)

    validate_manifest(manifest, artifacts)
    assert manifest["blocks"] == []
    assert manifest["assets"] == []
    assert manifest["warnings"] == [
        {
            "page": 1,
            "kind": "empty_page",
            "count": 1,
            "message": "第 1 页未识别到文本、表格或图片",
        }
    ]


def test_bbox_is_written_in_top_left_points(tmp_path: Path) -> None:
    page = {
        "blocks": [
            {"kind": "text", "text": "x", "bbox": {"l": 0.1, "t": 0.25, "r": 0.5, "b": 0.5}}
        ]
    }
    client = ScriptedVisionClient(page_answers=[page])

    manifest, _ = _run_converter(tmp_path, client)

    block = manifest["blocks"][0]
    assert block["bbox"] == {
        "l": 40.0,
        "t": 150.0,
        "r": 200.0,
        "b": 300.0,
        "coord_origin": "TOPLEFT",
    }
    assert block["locations"][0]["charspan"] == [0, len(block["text"])]

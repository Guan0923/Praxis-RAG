def test_converter_builds_a_valid_contract_manifest(tmp_path: Path) -> None:
    client = ScriptedVisionClient(page_answers=[PAGE_ONE, PAGE_TWO])

    manifest, artifacts = _run_converter(tmp_path, client, pages=2)

    validate_manifest(manifest, artifacts)
    json.loads(json.dumps(manifest))  # the Go backend decodes exactly this payload

    drafts = [block["kind"] for block in manifest["blocks"]]
    assert drafts == ["title", "text", "formula", "table", "picture", "section_header", "text"]
    assert [block["order"] for block in manifest["blocks"]] == list(range(len(drafts)))
    refs = [block["ref"] for block in manifest["blocks"]]
    assert refs == [
        "#/texts/0",
        "#/texts/1",
        "#/texts/2",
        "#/tables/0",
        "#/pictures/0",
        "#/texts/3",
        "#/texts/4",
    ]
    assert len(set(refs)) == len(refs)

    formula = manifest["blocks"][2]
    assert formula["latex"] == "E = mc^2"
    assert formula["text"].startswith("$$\n")
    assert formula["latex"] in formula["text"]
    assert formula["equation_number"] == "3"
    assert formula["original_text"] == "E = mc^2 (3)"

    table_asset = next(asset for asset in manifest["assets"] if asset["kind"] == "table")
    assert table_asset["image_file"] is None
    assert table_asset["table"]["rows"] == [["Metric", "Value"], ["Accuracy", "0.93"]]
    assert table_asset["table"]["num_rows"] == 2
    assert table_asset["table"]["num_cols"] == 2
    assert table_asset["table"]["orientation"] == "horizontal"
    assert len(table_asset["table"]["cells"]) == 4

    picture_asset = next(asset for asset in manifest["assets"] if asset["kind"] == "picture")
    assert picture_asset["image_file"] == "pictures/picture-0.png"
    assert picture_asset["caption"] == "Figure 1: pipeline overview"
    assert picture_asset["caption_source"] == "document"
    image = artifacts / picture_asset["image_file"]
    assert image.is_file()
    assert image.read_bytes().startswith(b"\x89PNG\r\n\x1a\n")
    bbox = picture_asset["bbox"]
    assert bbox["coord_origin"] == "TOPLEFT"
    assert 0 <= bbox["l"] < bbox["r"] <= 400
    assert 0 <= bbox["t"] < bbox["b"] <= 600

    parser = manifest["parser"]
    assert parser["converter"] == "vision"
    assert parser["backend"] == "openai-compatible"
    assert parser["model"] == "qwen-vl"
    assert parser["endpoint"] == "vlm.test"
    assert parser["prompt_version"] == "vision-v1"
    assert "sk-secret" not in json.dumps(manifest)

    metrics = manifest["metrics"]
    assert metrics["pages"] == 2
    assert metrics["vision_requests"] == 2
    assert metrics["vision_failures"] == 0
    # Every page image sent to the model is a JPEG.
    page_calls = [call for call in client.calls if call["kind"] == "page"]
    assert len(page_calls) == 2
    assert all(call["image"].startswith(b"\xff\xd8") for call in page_calls)



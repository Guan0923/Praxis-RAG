def test_request_shape_and_headers() -> None:
    captured: dict = {}
    jpeg = b"\xff\xd8\xff\xe0fake-jpeg-body"

    def handler(request: httpx.Request) -> httpx.Response:
        captured["url"] = str(request.url)
        captured["headers"] = dict(request.headers)
        captured["body"] = json.loads(request.content)
        return httpx.Response(200, json={"choices": [{"message": {"content": "a description"}}]})

    answer = _client(handler).complete("describe this image", jpeg)

    assert answer == "a description"
    assert captured["url"] == "http://vlm.internal:8443/v1/chat/completions"
    assert captured["headers"]["authorization"] == "Bearer sk-secret"
    body = captured["body"]
    assert body["model"] == "qwen-vl"
    assert body["temperature"] == 0
    assert body["max_tokens"] == 4096
    content = body["messages"][0]["content"]
    assert content[0] == {"type": "text", "text": "describe this image"}
    data_url = content[1]["image_url"]["url"]
    assert data_url.startswith("data:image/jpeg;base64,")
    assert base64.b64decode(data_url.split(",", 1)[1]) == jpeg



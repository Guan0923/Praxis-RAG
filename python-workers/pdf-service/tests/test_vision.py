def _client(handler, settings: VisionSettings | None = None) -> VisionClient:
    settings = settings or VisionSettings("http://vlm.internal:8443/v1", "sk-secret", "qwen-vl")
    return VisionClient(settings, transport=httpx.MockTransport(handler))


def _run_converter(
    tmp_path: Path,
    client: ScriptedVisionClient,
    *,
    options=None,
    concurrency: int = 1,
    pages: int = 1,
    api_key: str = "sk-secret",
):
    settings = VisionSettings(
        "http://vlm.test/v1",
        api_key,
        "qwen-vl",
        timeout=120.0,
        concurrency=concurrency,
    )
    converter = VisionConverter(
        settings, client_factory=lambda resolved: client, page_dpi=100
    )
    source = tmp_path / "source.pdf"
    source.write_bytes(build_pdf(pages=pages))
    artifacts = tmp_path / "artifacts"
    scratch = tmp_path / "scratch"
    manifest = converter.convert(source, artifacts, scratch, options=options)
    return manifest, artifacts


